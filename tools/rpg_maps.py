def cave(rows, torches, extra):
    m = Grid(len(rows[0]), len(rows), "#")
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            m.set(x, y, ch)
    for x, y in torches:
        if m.g[y][x] == "#":
            m.set(x, y, "i")
    for x, y, ch in extra:
        m.set(x, y, ch)
    return m


