"""아르카디아 지도 생성기.

건물(벽·바닥·문)과 가구를 좌표로 찍어서 지도를 만들고 RpgMaps.java 로 출력한다.
실행: python3 tools/rpg_maps.py

타일
  . 풀밭  T 숲/나무  f 꽃  = 길  B 다리  ~ 물  ^ 산   V 마을  K 성  O 동굴
  ; 마을 풀밭  , 돌바닥/흙길  : 나무 바닥  + 문(열린 입구)
  # 돌벽  H 나무벽  r 융단  | 계산대  b 침대  t 탁자  k 책장  o 통  x 상자
  F 울타리  Q 우물  Y 표지판  P 긴 의자  A 제단  M 벽화  g 밭  N 분수  L 가로등  Z 옥좌  j 덤불
  W 차원 이동 장치  X 출구  S 내려가는 계단  U 올라가는 계단  C 보물상자  i 횃불  e 쓰러진 방패
"""
import os


class Grid:
    def __init__(self, w, h, fill):
        self.w, self.h = w, h
        self.g = [[fill] * w for _ in range(h)]

    def set(self, x, y, ch):
        assert 0 <= x < self.w and 0 <= y < self.h, (x, y)
        self.g[y][x] = ch

    def fill(self, x0, y0, x1, y1, ch):
        for y in range(y0, y1 + 1):
            for x in range(x0, x1 + 1):
                self.set(x, y, ch)

    def room(self, x0, y0, x1, y1, wall, floor):
        self.fill(x0, y0, x1, y1, wall)
        self.fill(x0 + 1, y0 + 1, x1 - 1, y1 - 1, floor)

    def border(self, ch):
        for x in range(self.w):
            self.set(x, 0, ch)
            self.set(x, self.h - 1, ch)
        for y in range(self.h):
            self.set(0, y, ch)
            self.set(self.w - 1, y, ch)

    def rows(self):
        return ["".join(r) for r in self.g]


# ---------------------------------------------------------------- 청와대 집무실 + 금고
def office():
    m = Grid(17, 10, "#")
    m.fill(1, 1, 12, 8, ",")
    m.fill(14, 1, 15, 6, ",")
    m.set(13, 5, "+")                       # 금고 문
    for x in (1, 2, 10, 11):
        m.set(x, 1, "k")                    # 책장
    m.set(6, 1, "M")                        # 역대 대통령 초상화
    m.fill(4, 3, 8, 3, "|")                 # 대통령 책상
    m.set(1, 7, "o")                        # 화분 대신 통
    m.set(15, 2, "W")                       # 차원 이동 장치
    m.set(15, 4, "x")                       # 금고 기록 상자
    m.fill(3, 6, 4, 6, "P")                 # 응접 의자
    m.fill(8, 6, 9, 6, "P")
    m.set(6, 6, "t")
    return m


