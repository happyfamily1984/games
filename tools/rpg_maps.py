def check():
    maps = all_maps()
    for name, grid in maps.items():
        assert all(len(r) == grid.w for r in grid.rows()), name
    # 3장 지도: 입구에서 중요한 칸에 갈 수 있는지
    def can(name, start, *targets):
        r = reachable(maps[name], start)
        for t in targets:
            assert any((t[0] + dx, t[1] + dy) in r for dx, dy in ((0, 0), (1, 0), (-1, 0), (0, 1), (0, -1))), (name, t)
    can("WORLD3", (8, 18), (14, 16), (14, 8), (24, 13), (16, 19))
    can("LAVA1", (11, 13), (4, 11), (22, 1), (13, 5))
    can("LAVA2", (11, 12), (5, 4), (21, 3))
    can("FORT1", (11, 13), (18, 8), (6, 5))
    can("FORT2", (16, 12), (1, 7), (21, 6), (12, 8))
    can("FORT3", (12, 11), (11, 6), (22, 6))
    can("IGNA", (12, 18), (6, 7), (19, 8), (6, 12), (19, 12), (4, 14), (8, 14), (19, 14))


