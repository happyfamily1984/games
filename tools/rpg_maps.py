def reachable(grid, start):
    """시작점에서 걸어서 갈 수 있는 칸 (지도 검사용)"""
    blocked = set("#~^H|WCbtkoxFQYPAMgNLZijevqlJ")
    seen, todo = {start}, [start]
    while todo:
        x, y = todo.pop()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            nx, ny = x + dx, y + dy
            if 0 <= nx < grid.w and 0 <= ny < grid.h and (nx, ny) not in seen and grid.g[ny][nx] not in blocked:
                seen.add((nx, ny))
                todo.append((nx, ny))
    return seen


